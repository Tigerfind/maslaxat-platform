// Специализации хранятся канонически (по-русски — так фильтрует каталог и хранит бэкенд),
// а показываются на языке интерфейса. Здесь только маппинг значение → slug → i18n-ключ.
const SPEC_SLUG = {
  'Гражданское право': 'civil',
  'Семейное право': 'family',
  'Трудовое право': 'labor',
  'Уголовное право': 'criminal',
  'Коммерческое право': 'commercial',
  'Налоговое право': 'tax',
  'Административное право': 'administrative',
  'Земельное право': 'land',
  'Корпоративное право': 'corporate',
  'Интеллектуальная собственность': 'ip',
  'Жилищное право': 'housing',
  'Страховое право': 'insurance',
};

// Возвращает переведённую подпись специализации; для неизвестных — исходное значение.
export const specLabel = (t, value) => {
  const slug = SPEC_SLUG[value];
  return slug ? t('specNames.' + slug) : value;
};

export default specLabel;
